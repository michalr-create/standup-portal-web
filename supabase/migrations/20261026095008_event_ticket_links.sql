-- Extra ticket portals for one gig. events.ticket_url / ticket_provider /
-- external_id stays the primary link. Rows here are additional storefronts.
-- Public read follows the parent event: anon and authenticated can select a
-- link only when that event is an upcoming on_sale or sold_out listing.
-- No public INSERT, UPDATE, or DELETE.

alter table public.events drop constraint events_ticket_provider_check;

alter table public.events add constraint events_ticket_provider_check check (
  ticket_provider in (
    'kupbilecik',
    'going',
    'ebilet',
    'ticketmaster',
    'bilety24',
    'eventim',
    'biletomat',
    'other'
  )
);

create table public.event_ticket_links (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events (id) on delete cascade,
  ticket_url text not null,
  ticket_provider text not null,
  external_id text not null,
  is_primary boolean not null default false,
  constraint event_ticket_links_provider_check check (
    ticket_provider in (
      'kupbilecik',
      'going',
      'ebilet',
      'ticketmaster',
      'bilety24',
      'eventim',
      'biletomat',
      'other'
    )
  ),
  constraint event_ticket_links_provider_external_id_key unique (ticket_provider, external_id)
);

create index event_ticket_links_event_id_idx on public.event_ticket_links (event_id);
create index event_ticket_links_ticket_provider_idx on public.event_ticket_links (ticket_provider);

alter table public.event_ticket_links enable row level security;

create policy "Public can read listed event ticket links"
on public.event_ticket_links
for select
to anon, authenticated
using (
  exists (
    select 1
    from public.events
    where events.id = event_ticket_links.event_id
      and events.status in ('on_sale', 'sold_out')
      and events.starts_at >= now()
  )
);

revoke all on table public.event_ticket_links from anon, authenticated;
grant select on table public.event_ticket_links to anon, authenticated;
grant all on table public.event_ticket_links to service_role;

do $$
declare
  seq text := pg_get_serial_sequence('public.event_ticket_links', 'id');
begin
  execute format('revoke all on sequence %s from anon, authenticated', seq);
end $$;
