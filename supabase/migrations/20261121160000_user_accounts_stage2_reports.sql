-- Stage 2, reports: logged-in readers can file a missing video, a wrong
-- tag/person/format, or a new open mic. Admins see every row and set status.
-- No ratings. Apply this file yourself. Safe to re-run.
-- The browser never uses the service role.

create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null,
  content_item_id bigint references public.content_items (id) on delete set null,
  url text,
  message text not null default '',
  status text not null default 'new',
  created_at timestamptz not null default now(),
  constraint content_reports_kind_check check (
    kind in ('missing_video', 'wrong_meta', 'new_open_mic')
  ),
  constraint content_reports_status_check check (
    status in ('new', 'accepted', 'dismissed')
  ),
  constraint content_reports_message_len check (char_length(message) <= 2000),
  constraint content_reports_url_len check (url is null or char_length(url) <= 500),
  constraint content_reports_shape_check check (
    (kind = 'missing_video' and url is not null and content_item_id is null)
    or (kind = 'wrong_meta' and content_item_id is not null and char_length(btrim(message)) > 0)
    or (kind = 'new_open_mic' and char_length(btrim(message)) > 0)
  )
);

create index if not exists content_reports_user_id_idx
  on public.content_reports (user_id, created_at);

create index if not exists content_reports_content_item_id_idx
  on public.content_reports (content_item_id);

create index if not exists content_reports_created_at_idx
  on public.content_reports (created_at desc);

alter table public.content_reports enable row level security;

drop policy if exists "Users insert own reports" on public.content_reports;
create policy "Users insert own reports"
on public.content_reports
for insert
to authenticated
with check ((select auth.uid()) = user_id and status = 'new');

drop policy if exists "Users read own reports and admins read all" on public.content_reports;
create policy "Users read own reports and admins read all"
on public.content_reports
for select
to authenticated
using ((select auth.uid()) = user_id or (select public.is_admin()));

drop policy if exists "Admins update report status" on public.content_reports;
create policy "Admins update report status"
on public.content_reports
for update
to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

revoke all on table public.content_reports from anon, authenticated;
grant select, insert on table public.content_reports to authenticated;
grant update (status) on table public.content_reports to authenticated;
grant all on table public.content_reports to service_role;

do $$
declare
  seq text := pg_get_serial_sequence('public.content_reports', 'id');
begin
  if seq is not null then
    execute format('revoke all on sequence %s from anon', seq);
    execute format('grant usage, select on sequence %s to authenticated', seq);
  end if;
end $$;

create or replace function public.enforce_content_report_daily_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  filed integer;
  day_start timestamptz;
begin
  day_start := (
    date_trunc('day', (select now() at time zone 'Europe/Warsaw'))
    at time zone 'Europe/Warsaw'
  );
  select count(*) into filed
  from public.content_reports
  where user_id = new.user_id
    and created_at >= day_start;
  if filed >= 10 then
    raise exception 'content_report_daily_limit' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

revoke all on function public.enforce_content_report_daily_limit() from public, anon, authenticated;

drop trigger if exists content_reports_daily_limit on public.content_reports;
create trigger content_reports_daily_limit
  before insert on public.content_reports
  for each row
  execute function public.enforce_content_report_daily_limit();
