-- ---------------------------------------------------------------------------
-- One row per user, kind, and subject. Dispatch writes it after a successful
-- send. Authenticated clients cannot insert here, so they cannot suppress
-- a notification by logging it themselves.
-- ---------------------------------------------------------------------------

create table if not exists public.notification_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null,
  ref_id text not null,
  sent_at timestamptz not null default now(),
  constraint notification_log_user_kind_ref_key unique (user_id, kind, ref_id),
  constraint notification_log_kind_check check (
    kind in ('new_content', 'new_event', 'event_reminder')
  ),
  constraint notification_log_ref_id_check check (char_length(ref_id) between 1 and 64)
);

create index if not exists notification_log_user_kind_idx
  on public.notification_log (user_id, kind, sent_at desc);

