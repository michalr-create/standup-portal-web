-- Stage 3: Web Push only. No email, no ratings.
-- Apply this file yourself. It does not schedule cron and it does not call
-- the site. Safe to re-run. The browser never uses the service role.
--
-- Quiet hours are intentionally omitted.
--
-- content_items has no approval timestamp. created_at is the ingest time,
-- often while the row is still pending, so a cursor on created_at would miss
-- later approvals. approved_at is stamped when a row becomes publicly
-- approved. Existing approved rows are backfilled to created_at so the first
-- dispatch (which only stores "now" and sends nothing) cannot treat the
-- catalog as new.

-- ---------------------------------------------------------------------------
-- Subscriptions. One push endpoint belongs to one account. The endpoint is a
-- capability URL, so anon cannot read or write it.
-- ---------------------------------------------------------------------------

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  user_agent text,
  created_at timestamptz not null default now(),
  last_success_at timestamptz,
  failure_count integer not null default 0,
  constraint push_subscriptions_endpoint_key unique (endpoint),
  constraint push_subscriptions_endpoint_check check (
    char_length(endpoint) between 12 and 2000
    and endpoint like 'https://%'
  ),
  constraint push_subscriptions_keys_check check (
    char_length(p256dh) between 8 and 200
    and char_length(auth) between 8 and 200
  ),
  constraint push_subscriptions_user_agent_check check (
    user_agent is null or char_length(user_agent) <= 400
  ),
  constraint push_subscriptions_failure_count_check check (failure_count >= 0)
);

create index if not exists push_subscriptions_user_id_idx
  on public.push_subscriptions (user_id);

alter table public.push_subscriptions enable row level security;

drop policy if exists "Users can read own push subscriptions" on public.push_subscriptions;
create policy "Users can read own push subscriptions"
on public.push_subscriptions
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert own push subscriptions" on public.push_subscriptions;
create policy "Users can insert own push subscriptions"
on public.push_subscriptions
for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update own push subscriptions" on public.push_subscriptions;
create policy "Users can update own push subscriptions"
on public.push_subscriptions
for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own push subscriptions" on public.push_subscriptions;
create policy "Users can delete own push subscriptions"
on public.push_subscriptions
for delete
to authenticated
using ((select auth.uid()) = user_id);

revoke all on table public.push_subscriptions from public, anon, authenticated;
grant select, insert, delete on table public.push_subscriptions to authenticated;
grant update (p256dh, auth, user_agent) on table public.push_subscriptions to authenticated;
grant all on table public.push_subscriptions to service_role;

