-- ---------------------------------------------------------------------------
-- Last successful scan. id = 'dispatch'. No row means "never ran": the route
-- inserts ran_at = now() and sends nothing. lease_until stops a second cron
-- tick from overlapping a run that is still sending.
-- ---------------------------------------------------------------------------

create table if not exists public.push_cursor (
  id text primary key,
  ran_at timestamptz not null,
  lease_until timestamptz,
  constraint push_cursor_id_check check (char_length(id) between 1 and 64)
);

alter table public.push_cursor enable row level security;

revoke all on table public.push_cursor from public, anon, authenticated;
grant all on table public.push_cursor to service_role;

create or replace function public.acquire_push_lease(p_lease_until timestamptz)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_ran timestamptz;
begin
  update public.push_cursor as c
     set lease_until = p_lease_until
   where c.id = 'dispatch'
     and (c.lease_until is null or c.lease_until <= now())
  returning c.ran_at into current_ran;
  return current_ran;
end;
$$;

revoke all on function public.acquire_push_lease(timestamptz) from public, anon, authenticated;
grant execute on function public.acquire_push_lease(timestamptz) to service_role;

do $$
declare
  seq text;
begin
  seq := pg_get_serial_sequence('public.push_subscriptions', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon', seq);
    execute format('grant usage, select on sequence %s to authenticated, service_role', seq);
  end if;
  seq := pg_get_serial_sequence('public.notification_log', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq);
    execute format('grant usage, select on sequence %s to service_role', seq);
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- When a row becomes a public, unmerged approval, stamp approved_at.
-- Re-approving after a reject or an unmerge stamps a new time. Ordinary
-- edits of an already approved row do not.
-- ---------------------------------------------------------------------------

alter table public.content_items
  add column if not exists approved_at timestamptz;

create index if not exists content_items_approved_dispatch_idx
  on public.content_items (approved_at)
  where status = 'approved' and merged_into_id is null and approved_at is not null;

create index if not exists events_created_at_idx
  on public.events (created_at);

-- Backfill before the trigger exists on a fresh database. On a re-run the
-- trigger is already there; it keeps this created_at value because the row
-- was already approved (see the function below).
update public.content_items
   set approved_at = coalesce(created_at, now())
 where status = 'approved'
   and merged_into_id is null
   and approved_at is null;

create or replace function public.stamp_content_approved_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'approved' and new.merged_into_id is null then
    if tg_op = 'INSERT'
       or old.status is distinct from 'approved'
       or old.merged_into_id is not null then
      new.approved_at := now();
    elsif new.approved_at is null then
      new.approved_at := coalesce(new.created_at, now());
    end if;
  else
    new.approved_at := null;
  end if;
  return new;
end;
$$;

revoke all on function public.stamp_content_approved_at() from public, anon, authenticated;

drop trigger if exists content_items_stamp_approved_at on public.content_items;
create trigger content_items_stamp_approved_at
  before insert or update of status, merged_into_id, approved_at
  on public.content_items
  for each row
  execute function public.stamp_content_approved_at();
