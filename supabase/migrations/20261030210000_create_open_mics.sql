-- Open mics are a separate catalog from public.events /trasy.
-- Idempotent and additive: re-running does not touch events or content_items.
--
-- Visibility (decided on purpose):
--   anon/authenticated can read open_mics where status is active or to_verify.
--   to_verify stays public. The page badges those cycles "do potwierdzenia"
--   instead of hiding a night we have not re-checked. pending, inactive, and
--   rejected stay hidden, the same idea as content_items moderation.
--   anon/authenticated can read open_mic_dates only when moderation_status
--   is approved AND the parent cycle is visible. open_mic_id null means the
--   import has no matched cycle yet, so those rows stay hidden.
--
-- There is no INSERT/UPDATE/DELETE policy. The public form "Dodaj swój open mic"
-- is a server action on the service role. It validates the payload, rejects a
-- filled honeypot, and forces status = 'pending'. service_role bypasses RLS.
--
-- language is pl, en, or pl/en (null if a submission left it blank).
-- The researched nights are Polish-only or English-only. pl/en is one bilingual
-- room (both languages the same night), not a second table. Short codes match
-- the badge (PL, EN, PL/EN).
--
-- open_mic_dates.status mirrors public.events.status, not the raw feed token:
--   on_sale    scheduled and bookable (schema.org EventScheduled, "w sprzedaży")
--   sold_out   listed, no tickets left
--   cancelled  called off
--   unknown    happening, ticket state not classified (free / signup-only)
-- The page lists on_sale, sold_out, and unknown, and hides cancelled plus
-- past starts_at. RLS does not repeat that filter: approved history stays
-- readable if a later archive asks for it.
--
-- id is GENERATED BY DEFAULT AS IDENTITY so a seed can pass explicit ids.
-- unique (provider, external_id) treats null external_id as distinct, so
-- several manual rows without a provider id can coexist. Kupbilecik ids cannot.
--
-- submitted_by_email is contact for the public form. Column grants omit it
-- from anon/authenticated so PostgREST cannot select it. Do not add it to
-- the public select list.

create table if not exists public.open_mics (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  city text,
  venue text,
  address text,
  lat double precision,
  lng double precision,
  recurrence_text text,
  language text,
  signup_info text,
  signup_url text,
  rules text,
  audience_price_text text,
  organizer text,
  source_urls text[] not null default '{}',
  status text not null default 'pending',
  last_confirmed_at timestamptz,
  submitted_by_email text,
  created_at timestamptz not null default now(),
  constraint open_mics_slug_key unique (slug),
  constraint open_mics_name_check check (char_length(btrim(name)) > 0),
  constraint open_mics_slug_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint open_mics_language_check check (
    language is null or language in ('pl', 'en', 'pl/en')
  ),
  constraint open_mics_status_check check (
    status in ('pending', 'active', 'to_verify', 'inactive', 'rejected')
  ),
  constraint open_mics_coords_check check (
    (lat is null and lng is null)
    or (
      lat is not null and lng is not null
      and lat >= -90 and lat <= 90
      and lng >= -180 and lng <= 180
    )
  )
);

create table if not exists public.open_mic_dates (
  id bigint generated by default as identity primary key,
  open_mic_id bigint references public.open_mics (id) on delete cascade,
  title text,
  starts_at timestamptz not null,
  city text,
  venue text,
  provider text not null,
  external_id text,
  url text,
  status text not null default 'unknown',
  moderation_status text not null default 'pending',
  source_checked_at timestamptz,
  created_at timestamptz not null default now(),
  constraint open_mic_dates_provider_check check (
    provider in ('kupbilecik', 'other')
  ),
  constraint open_mic_dates_status_check check (
    status in ('on_sale', 'sold_out', 'cancelled', 'unknown')
  ),
  constraint open_mic_dates_moderation_status_check check (
    moderation_status in ('pending', 'approved', 'rejected')
  ),
  constraint open_mic_dates_external_id_check check (
    external_id is null or char_length(btrim(external_id)) > 0
  ),
  constraint open_mic_dates_provider_external_id_key unique (provider, external_id)
);

create index if not exists open_mics_city_idx on public.open_mics (city);
create index if not exists open_mics_status_idx on public.open_mics (status);
create index if not exists open_mic_dates_city_idx on public.open_mic_dates (city);
create index if not exists open_mic_dates_status_idx on public.open_mic_dates (status);
create index if not exists open_mic_dates_starts_at_idx on public.open_mic_dates (starts_at);
create index if not exists open_mic_dates_open_mic_id_idx on public.open_mic_dates (open_mic_id);
create index if not exists open_mic_dates_moderation_status_idx on public.open_mic_dates (moderation_status);

alter table public.open_mics enable row level security;
alter table public.open_mic_dates enable row level security;

drop policy if exists "Public can read listed open mics" on public.open_mics;
create policy "Public can read listed open mics"
on public.open_mics
for select
to anon, authenticated
using (status in ('active', 'to_verify'));

drop policy if exists "Public can read approved open mic dates" on public.open_mic_dates;
create policy "Public can read approved open mic dates"
on public.open_mic_dates
for select
to anon, authenticated
using (
  moderation_status = 'approved'
  and exists (
    select 1
    from public.open_mics parent
    where parent.id = open_mic_dates.open_mic_id
      and parent.status in ('active', 'to_verify')
  )
);

revoke all on table public.open_mics from public, anon, authenticated;
revoke all on table public.open_mic_dates from public, anon, authenticated;

grant select (
  id,
  name,
  slug,
  city,
  venue,
  address,
  lat,
  lng,
  recurrence_text,
  language,
  signup_info,
  signup_url,
  rules,
  audience_price_text,
  organizer,
  source_urls,
  status,
  last_confirmed_at,
  created_at
) on table public.open_mics to anon, authenticated;

grant select on table public.open_mic_dates to anon, authenticated;

grant all on table public.open_mics to service_role;
grant all on table public.open_mic_dates to service_role;

do $$
declare
  seq text;
begin
  seq := pg_get_serial_sequence('public.open_mics', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq);
  end if;
  seq := pg_get_serial_sequence('public.open_mic_dates', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq);
  end if;
end $$;
