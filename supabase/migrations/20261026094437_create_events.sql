-- Stand-up tour dates. One ticket link per event (no event_ticket_links).
-- Public read matches content_items: a SELECT policy for the anon client,
-- scoped to rows the listing may show. sold_out stays readable so /trasy can
-- filter availability. cancelled and unknown stay hidden, the way pending and
-- rejected content_items stay hidden. Past rows stay hidden (starts_at >= now()).
-- service_role bypasses RLS and is how moderators seed rows. No INSERT,
-- UPDATE, or DELETE policy, and those privileges are revoked from anon and
-- authenticated.

create table public.events (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people (id),
  title text,
  starts_at timestamptz not null,
  city text not null,
  venue text not null,
  venue_address text,
  price_from numeric,
  currency text not null default 'PLN',
  status text not null default 'unknown',
  ticket_url text not null,
  ticket_provider text not null,
  external_id text not null,
  source_checked_at timestamptz,
  created_at timestamptz not null default now(),
  constraint events_status_check check (
    status in ('on_sale', 'sold_out', 'cancelled', 'unknown')
  ),
  constraint events_ticket_provider_check check (
    ticket_provider in ('kupbilecik', 'going', 'other')
  ),
  constraint events_ticket_provider_external_id_key unique (ticket_provider, external_id)
);

create index events_starts_at_idx on public.events (starts_at);
create index events_person_id_idx on public.events (person_id);
create index events_city_idx on public.events (city);
create index events_status_idx on public.events (status);

alter table public.events enable row level security;

create policy "Public can read listed events"
on public.events
for select
to anon, authenticated
using (
  status in ('on_sale', 'sold_out')
  and starts_at >= now()
);

revoke all on table public.events from anon, authenticated;
grant select on table public.events to anon, authenticated;
grant all on table public.events to service_role;

do $$
declare
  seq text := pg_get_serial_sequence('public.events', 'id');
begin
  execute format('revoke all on sequence %s from anon, authenticated', seq);
end $$;
